// Build a Mega Drive ROM that plays one score through the SHIPPED driver glue.
//
//   node tools/build-verify-rom.mjs <score.mmlisp|score.mmb> [-o out.md]
//
// The ROM is a measurement jig, not a product. What ships to a user is still
// tools/install-sgdk.mjs into their SGDK project; this exists so that the same
// mmlispdrv.c / mmlispseq.c / engine image can be run by a script, in a
// container, without SGDK and without anybody's desktop — see
// verify-rom/README.md.
//
// The toolchain is Debian/Ubuntu's m68k-linux-gnu, because `apt-get install
// gcc-m68k-linux-gnu` is a thing a CI job can do and installing SGDK is not.
// Nothing links against its libc: -ffreestanding -nostdlib, our own crt, our
// own linker script.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// ── The sample clock, set before anything reads it ─────────────────────────
// PCM_SPG and TIMER_B_K decide the DAC's rate, and they are read at MODULE LOAD
// by live/src/mmb.js and tools/gen-mixer.mjs — so they have to be in the
// environment before the first import that reaches them, which is why the
// sequencer toolchain is pulled in dynamically further down.
//
// The defaults are the branch's only working configuration: every sample gated,
// 3,329 Hz (plan-68k-split.md, "THE STANDING CONSTRAINT"). Timer B's shortest
// period is 16 FM samples, so per-sample gating requires PCM_SAMPLES_PER_GATE=1,
// and 9,987 Hz (TIMER_B_K=16) is currently broken by the producer/consumer DAC.
// Both knobs must agree across the MMB's baked sample bank, the generated mixer
// and mml_rate.h, or mml_load_samples refuses the bank on its stamp and every
// PCM note is silently dropped — which is what a mismatched build looks like.
process.env.PCM_SPG ??= "1";
process.env.TIMER_B_K ??= "1";
// PCM_TIMER=A with PCM_FM=<FM samples a DAC sample> is the Timer A shape: the
// period is (1024 - NA) FM samples across a 10-bit register, so the rate is any
// value up to 53,267 Hz instead of Timer B's ceiling of 3,329. Both defaults
// stay on Timer B, which is what a score with a CSM track has to use.
if (process.env.PCM_TIMER?.toUpperCase() === "A") process.env.PCM_FM ??= "16";

const here = dirname(fileURLToPath(import.meta.url));
const drv = join(here, "..");
const romdir = join(drv, "verify-rom");
const out = join(drv, "out", "verify-rom");

const CC = process.env.M68K_CC ?? "m68k-linux-gnu-gcc";
const OBJCOPY = process.env.M68K_OBJCOPY ?? "m68k-linux-gnu-objcopy";
const NM = process.env.M68K_NM ?? "m68k-linux-gnu-nm";

const argv = process.argv.slice(2);
const oIdx = argv.indexOf("-o");
const outRom = oIdx >= 0 ? argv[oIdx + 1] : null;
const score = argv.find((a, i) => !a.startsWith("-") && argv[i - 1] !== "-o");
if (!score) {
  console.error("usage: node tools/build-verify-rom.mjs <score.mmlisp|score.mmb> [-o out.md]");
  process.exit(2);
}

function run(cmd, args) {
  try {
    return execFileSync(cmd, args, { cwd: romdir, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] });
  } catch (e) {
    console.error(`${cmd} ${args.join(" ")}\n${e.stderr ?? e.message}`);
    process.exit(1);
  }
}

mkdirSync(out, { recursive: true });

// ── The engine image and the rate tables ───────────────────────────────────
// Regenerated before anything is compiled, so a ROM can never be built from a
// stale image or a stale stamp while the source moved under it.
run("node", [join(here, "gen-c-tables.mjs")]);
run("node", [join(here, "gen-mixer.mjs")]);
run("node", [join(here, "emit-bin.mjs")]);

// ── The score ──────────────────────────────────────────────────────────────
const { buildMmb } = await import("./mmb-build.mjs");
let mmb, sampleBank;
if (score.endsWith(".mmb")) {
  mmb = readFileSync(score);
  const smp = score.replace(/\.mmb$/, ".smp");
  sampleBank = existsSync(smp) ? readFileSync(smp) : new Uint8Array(0);
} else {
  ({ bytes: mmb, sampleBank } = buildMmb(resolve(score)));
  sampleBank ??= new Uint8Array(0);
}

// The blobs go in as C arrays rather than being appended to the image, so that
// the linker owns their placement — in particular the sample bank's 32 KB
// alignment, which the Z80's window makes load-bearing.
const carr = (name, bytes, attr = "") => {
  const rows = [];
  for (let i = 0; i < bytes.length; i += 16)
    rows.push("  " + [...bytes.subarray(i, i + 16)].map((b) => b.toString()).join(","));
  return `const unsigned char ${name}[]${attr} = {\n${rows.join(",\n")}\n};\n`;
};
writeFileSync(join(romdir, "song.c"),
  "/* GENERATED by tools/build-verify-rom.mjs — do not edit, do not commit. */\n"
  + `/* score: ${basename(score)} */\n`
  // 2-byte alignment is not cosmetic: the sequencer reads 16- and 32-bit fields
  // straight out of the MMB, and a 68000 takes an address error on an odd word
  // access — which presents as the program vanishing before it loads anything.
  // res/song.res spells the same requirement as its `2` field.
  + carr("song_mmb", mmb, " __attribute__((aligned(2)))")
  + (sampleBank.length
      ? carr("song_smp", sampleBank, ' __attribute__((section(".smp"), aligned(32768)))')
      : "const unsigned char song_smp[1] = {0};\n")
  + `const unsigned short song_has_smp = ${sampleBank.length ? 1 : 0};\n`);

// ── Compile ────────────────────────────────────────────────────────────────
const CFLAGS = [
  // -fno-store-merging is not optional, and -mstrict-align does NOT replace it.
  // This toolchain targets Linux/68020+, where an unaligned word access is
  // legal, so its store-merging pass turns
  //
  //     b[i] = v;  b[i+1] = v >> 8;      (mmlispseq.c packing a write record)
  //
  // into `ror.w #8,%d0; move.w %d0,-13(%fp)` — a word store at an ODD offset,
  // which a 68000 answers with an address error. It killed the ROM on the first
  // note dispatched, and `-mstrict-align` was verified NOT to prevent it: the
  // pass does not consult the target's alignment rules. Turning it off does.
  "-m68000", "-mstrict-align", "-fno-store-merging",
  "-Os", "-fomit-frame-pointer", "-fno-builtin",
  "-ffreestanding", "-nostdlib", "-fno-pic", "-Wall",
  "-DSGDK_GCC=1",
  `-I${romdir}`, `-I${join(drv, "tools", "sgdk-shim")}`,
  `-I${join(drv, "sgdk")}`, `-I${join(drv, "68k")}`,
];
const SOURCES = [
  "boot.s", "sys.c", "main.c", "song.c", "libgcc68000.c",
  join(drv, "sgdk", "mmlispdrv.c"),
  join(drv, "68k", "mmlispseq.c"),
  join(drv, "68k", "tables.c"),
];
const elf = join(out, "probe.elf");
// NOT -lgcc. The 68000 has no 32-bit multiply or divide so the compiler calls
// __mulsi3/__divsi3 for them, but this toolchain's only libgcc is built for a
// 68020 and its helpers use instructions a 68000 cannot decode — see
// verify-rom/libgcc68000.c, which supplies them instead.
run(CC, [...CFLAGS, "-T", join(romdir, "rom.ld"), "-o", elf, ...SOURCES, "-nodefaultlibs"]);

const romPath = outRom ? resolve(outRom) : join(out, "probe.md");
run(OBJCOPY, ["-O", "binary", "--gap-fill", "0xFF", elf, romPath]);

// ── Where the probe published itself ───────────────────────────────────────
// The frontend reads work RAM out of the core, so it needs this address and
// nothing else. Reporting it beats agreeing on a constant that then drifts.
const syms = run(NM, [elf]);
const line = syms.split("\n").find((l) => / [Bb] probe$/.test(l));
if (!line) { console.error("build-verify-rom: no `probe` symbol in the image"); process.exit(1); }
const probeAddr = parseInt(line.split(/\s+/)[0], 16);
const WORK_RAM = 0xff0000;

const meta = {
  rom: romPath,
  score: basename(score),
  pcmSpg: Number(process.env.PCM_SPG),
  timerBK: Number(process.env.TIMER_B_K),
  timer: (process.env.PCM_TIMER ?? "B").toUpperCase(),
  fmPerSample: Number(process.env.PCM_FM ?? 16 / Number(process.env.PCM_SPG)),
  probeWords: 20,
  mmbBytes: mmb.length,
  sampleBytes: sampleBank.length,
  probeAddr,
  probeOffset: probeAddr - WORK_RAM,
};
writeFileSync(romPath.replace(/\.[^.]+$/, "") + ".json", JSON.stringify(meta, null, 2) + "\n");

const romBytes = readFileSync(romPath).length;
console.log(`verify-rom: ${basename(romPath)} — ${romBytes} B`
  + ` · mmb ${mmb.length} B · samples ${sampleBank.length} B`
  + ` · Timer ${meta.timer}, ${meta.fmPerSample} FM samples a sample`
  + ` (${(53693175 / 7 / 144 / meta.fmPerSample).toFixed(0)} Hz)`
  + ` · probe @ 0x${probeAddr.toString(16)} (work RAM +0x${meta.probeOffset.toString(16)})`);
