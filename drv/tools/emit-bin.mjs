// Assemble the Z80 engine and emit the artifacts a 68k project links against:
//   drv/sgdk/mmlispdrv.bin      raw Z80 engine image
//   drv/sgdk/mmlispdrv_bin.h    the same image as a C array, plus the interface
//                               constants read out of the build's own configuration
//
// The image is uploaded to Z80 RAM at 0x0000 and is the whole of what the
// engine needs before its first sample: code, the level family, the phase
// table. What the 68000 compiles in besides the image is the small ABI below
// — where the pair page is, where the state block is, the opcodes — and every
// one of those numbers comes from the configuration the image was generated
// from (tools/build-engine.mjs), so the two cannot disagree.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildEngine } from "./build-engine.mjs";
import { PCM_BAKE_STAMP, PCM_RING_TARGET, PCM_FM_NUM, PCM_FM_DEN } from "../../live/src/mmb.js";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "sgdk");

const { bytes, header: H, cfg } = buildEngine();

// THE SEQUENCER'S CLOCK AND THE IMAGE'S MUST BE ONE. mml_rate.h (and every
// baked sample bank) comes from live/src/mmb.js; the image's rate from its own
// schedule. A mismatch plays the drums at the wrong pitch and refuses nothing,
// so it is refused here, and the header carries the stamp rate-mirrors reads.
const seqHz = (cfg.machine.masterHz * PCM_FM_DEN) / (1008 * PCM_FM_NUM);
if (Math.abs(seqHz - cfg.rateHz) > 1e-6)
  throw new Error(`emit-bin: the image runs at ${cfg.rateHz.toFixed(3)} Hz, the sequencer's clock (live/src/mmb.js) is ${seqHz.toFixed(3)} Hz`);

const rows = [];
for (let i = 0; i < bytes.length; i += 12) {
  rows.push(
    "    " +
      [...bytes.slice(i, i + 12)].map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ") +
      ",",
  );
}
const hex = (n) => `0x${n.toString(16).toUpperCase()}`;

writeFileSync(join(outDir, "mmlispdrv.bin"), bytes);
writeFileSync(
  join(outDir, "mmlispdrv_bin.h"),
  `// Generated by drv/tools/emit-bin.mjs — DO NOT EDIT BY HAND.
// MMLispDRV Z80 engine image, ${bytes.length} bytes, uploaded to Z80 RAM at 0x0000.
// ${cfg.stamp} — the one-voice pair-transport engine (docs/dac-engine-implementation.md R28 §63).
#ifndef MMLISPDRV_BIN_H
#define MMLISPDRV_BIN_H

#include <types.h>

// RATE-STAMP ${PCM_BAKE_STAMP} ${PCM_RING_TARGET} — the sample clock this image was built for (tools/rate-mirrors.mjs).
#define MMLISPDRV_BIN_SIZE       ${bytes.length}
#define MMLISPDRV_PROTO_VER      ${H.PROTO_VER}

// The pair page (R28 §63.3 D3): ${H.FIFO_PAIRS} {op, val} pairs the 68000 writes and the
// engine consumes once each, ${H.STEPS_PER_LAP} a lap of ${H.LAP_SAMPLES} samples at ${H.RATE_HZ.toFixed(2)} Hz.
#define MMLISPDRV_FIFO           ${hex(H.FIFO)}
#define MMLISPDRV_FIFO_PAIRS     ${H.FIFO_PAIRS}
#define MMLISPDRV_PAIRS_PER_GRAB ${H.PAIRS_PER_GRAB}   // what one grab writes, always (IDLE-padded), inside 1,500 master

// The PCM state block, in the globals page. Ops below OP_LIMIT are offsets into
// it: a pair {op, val} stores val at STATE + op. Ops >= OP_LIMIT are YM registers.
#define MMLISPDRV_STATE          ${hex(H.STATE)}
#define MMLISPDRV_OP_LIMIT       ${hex(H.OP_LIMIT)}
#define MMLISPDRV_OP_IDLE        ${hex(H.OPS.IDLE)}
#define MMLISPDRV_OP_LEVEL       ${hex(H.OPS.LEVEL)}   // absolute LUT page: LUT_PAGE + 0..LEVELS-1
#define MMLISPDRV_OP_MASTER      ${hex(H.OPS.MASTER)}
#define MMLISPDRV_OP_SRC_LO      ${hex(H.OPS.SRC_LO)}  // the sample's window address
#define MMLISPDRV_OP_SRC_HI      ${hex(H.OPS.SRC_HI)}
#define MMLISPDRV_OP_END_LO      ${hex(H.OPS.END_LO)}  // sampleEnd - 16 * step
#define MMLISPDRV_OP_END_HI      ${hex(H.OPS.END_HI)}
#define MMLISPDRV_OP_STEP        ${hex(H.OPS.STEP)}    // 1, 2, 4 or 8 bytes a sample
#define MMLISPDRV_OP_START       ${hex(H.OPS.START)}   // a NEW value here starts the voice at the next block
#define MMLISPDRV_OP_STOP        ${hex(H.OPS.STOP)}    // a new value here parks it
#define MMLISPDRV_OP_PORT        ${hex(H.OPS.PORT)}    // val 0/1: the port the following registers go to

// Z80-owned bytes the 68000 reads.
#define MMLISPDRV_FIFO_LO        ${hex(H.FIFO_LO)}   // the expander's next pair, as a byte offset into FIFO
#define MMLISPDRV_READY          ${hex(H.READY)}
#define MMLISPDRV_READY_MARK     ${hex(H.READY_MARK)}

// The level family: ${H.LEVELS} pages from LUT_PAGE, level k = k/${H.LEVELS - 1} of unity.
#define MMLISPDRV_LUT_PAGE       ${hex(H.LUT_PAGE)}
#define MMLISPDRV_LEVELS         ${H.LEVELS}
// Where a parked voice reads: the sample bank's top page must be silence.
#define MMLISPDRV_SILENCE        ${hex(H.SILENCE)}

// The runtime protocol's control block (written by the 68000 before the Z80 starts).
#define MMLISPDRV_CTL_BOOT_GEN       ${hex(H.CTL_BOOT_GEN)}
#define MMLISPDRV_CTL_PHASE_GEN      ${hex(H.CTL_PHASE_GEN)}
#define MMLISPDRV_CTL_COMMAND_COMMIT ${hex(H.CTL_COMMAND_COMMIT)}
#define MMLISPDRV_CTL_PHASE_COMMIT   ${hex(H.CTL_PHASE_COMMIT)}

const u8 mmlispdrv_bin[${bytes.length}] = {
${rows.join("\n")}
};

#endif
`,
);
console.log(
  `sgdk/mmlispdrv.bin + mmlispdrv_bin.h: ${bytes.length} bytes (code ${H.CODE_END} B) · proto ${H.PROTO_VER} · ${cfg.stamp}`,
);
