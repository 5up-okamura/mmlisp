#!/usr/bin/env node
// Each machine's parts at full level, as the preview plays them: one note at
// :vel 15 on each kind of channel a machine has (FM, a square, a wave, a
// sample), its peak in dBFS — what a conversion reads to keep a score's
// samples where they sat beside its melody (live/src/port/score-port.js, the
// mix). The probes: FM a single carrier at TL 0 (the OPLL its init-fm, a
// sine), a square or a wave the channel's own default, a sample a
// full-scale square 0.25 s long.
//   node scripts/gen-part-levels.mjs           writes live/src/machine/part-levels.js
//   node scripts/gen-part-levels.mjs --check   holds it to the renders (±1 dB)
import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileScoreFile } from "../../drv/tools/mmb-build.mjs";
import { bakedChipSamples, loadSamplesForIr } from "../../drv/tools/wav.mjs";
import { IRPlayer } from "../../live/src/player/ir-player.js";
import { renderWavSamples } from "../../live/src/export/export-wav.js";
import { TARGETS } from "../../live/src/machine/targets.js";
import { PORT_TARGETS } from "../../live/src/port/score-port.js";
import { bakeSampleBank, sampleBankKind } from "../../live/src/audio/sample-bank.js";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = join(repo, "live/src/machine/part-levels.js");
const dir = mkdtempSync(join(tmpdir(), "part-levels-"));

// A 16-bit mono WAV, a full-scale square at 200 Hz.
function probeWav(path) {
  const rate = 16000, n = rate / 4;
  const b = Buffer.alloc(44 + 2 * n);
  b.write("RIFF", 0); b.writeUInt32LE(36 + 2 * n, 4); b.write("WAVEfmt ", 8);
  b.writeUInt32LE(16, 16); b.writeUInt16LE(1, 20); b.writeUInt16LE(1, 22);
  b.writeUInt32LE(rate, 24); b.writeUInt32LE(2 * rate, 28); b.writeUInt16LE(2, 32); b.writeUInt16LE(16, 34);
  b.write("data", 36); b.writeUInt32LE(2 * n, 40);
  for (let i = 0; i < n; i++) b.writeInt16LE(Math.floor(i / 40) % 2 ? -32767 : 32767, 44 + 2 * i);
  writeFileSync(path, b);
}
probeWav(join(dir, "probe.wav"));

const FM4 = "(def-fm probe init-fm :alg 7 :tl1 0 :tl2 127 :tl3 127 :tl4 127 :ar1 31 :dr1 0 :sl1 0 :rr1 15)";
function probeOf(target, kind) {
  const t = TARGETS[target];
  const head = t.channelNames.find((h) => {
    const p = t.partOf(h);
    return p?.kind === kind && !p.kit && !(t.listsExpansions && t.chipOf(h).optional) && !/^fm3-/.test(h);
  });
  if (!head) return null;
  const p = t.partOf(head);
  const two = !!p.romNames;
  if (kind === "fm") return { head, src: `(def-score :target ${target})\n${two ? "" : FM4 + "\n"}(${head} ${two ? "init-fm" : "probe"} :vel 15 :oct 4 :len 1 a)` };
  if (kind === "sample") return { head, src: `(def-score :target ${target})\n(def-pcm probe :file "probe.wav")\n(${head} probe :vel 15 :len 4 c)` };
  return { head, src: `(def-score :target ${target})\n(${head} :vel 15 :oct 4 :len 1 a)` };
}

async function peakOf(src, part) {
  const file = join(dir, "probe.mmlisp");
  writeFileSync(file, src);
  const { ir, diagnostics } = compileScoreFile(file);
  const bad = diagnostics.filter((d) => d.severity === "error");
  assert.deepEqual(bad.map((d) => d.message), [], src);
  const target = TARGETS[ir.metadata?.target ?? "md"];
  const kind = sampleBankKind(target);
  let pcm = null;
  if (kind === "mmb" && ir.metadata.samples?.length) pcm = bakeSampleBank(ir, loadSamplesForIr(ir), target).pcm;
  else if (kind) {
    const { adpcm, frames } = bakedChipSamples(ir, target);
    pcm = adpcm ? { adpcm } : frames ? { [kind]: frames } : null;
  }
  const r = await renderWavSamples(new IRPlayer(() => {}).loadJSON(ir), { pcm, fadeSec: 0 });
  // A tone's steady part (past a square's key-on click); a sample from its
  // start (a DMC sample is over in a few hundredths).
  const from = Math.floor((part === "sample" ? 0.002 : 0.05) * r.sampleRate), to = Math.floor(0.2 * r.sampleRate);
  let peak = 0;
  for (const x of [r.L, r.R]) for (let i = from; i < Math.min(to, x.length); i++) peak = Math.max(peak, Math.abs(x[i]));
  return Math.round(20 * Math.log10(peak + 1e-9) * 10) / 10;
}

const table = {};
for (const target of PORT_TARGETS) {
  table[target] = {};
  for (const kind of ["fm", "tone", "wave", "sample"]) {
    const probe = probeOf(target, kind);
    if (probe) table[target][kind] = await peakOf(probe.src, kind);
  }
}
rmSync(dir, { recursive: true, force: true });

const text = `// Generated by tools/scripts/gen-part-levels.mjs — do not edit by hand.
// Each machine's parts at full level as the preview plays them: one note at
// :vel 15, its peak in dBFS (FM a single carrier, a square or a wave the
// channel's default, a sample a full-scale square). A conversion keeps a
// score's samples where they sat beside its melody by them (score-port.js).
export const PART_LEVELS = ${JSON.stringify(table, null, 2).replace(/"(\w+)":/g, "$1:")};
`;
if (process.argv.includes("--check")) {
  const { PART_LEVELS } = await import("../../live/src/machine/part-levels.js");
  for (const [t, kinds] of Object.entries(table))
    for (const [k, v] of Object.entries(kinds))
      assert.ok(Math.abs((PART_LEVELS[t]?.[k] ?? Infinity) - v) <= 1, `${t} ${k}: ${PART_LEVELS[t]?.[k]} in the table, ${v} rendered — npm run gen:part-levels`);
  console.log("check:part-levels ok");
} else {
  writeFileSync(OUT, text);
  console.log(text);
}
