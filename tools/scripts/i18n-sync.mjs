#!/usr/bin/env node
// The translations of the Live app's reference and snippets, kept in step
// with the English (live/src/i18n.js explains what is translated and why).
//
//   node scripts/i18n-sync.mjs                   check: every pack complete and current
//   node scripts/i18n-sync.mjs --todo ja         the texts ja still needs, as JSON on stdout
//   node scripts/i18n-sync.mjs --apply ja f.json  merge translations in, drop the orphans
//
// The English texts are read from where the app reads them: reference.js and
// the snippets' leading comments. A pack (live/src/i18n/<lang>.js) holds, per
// text, [hash of the English, translation]; a text whose English changed is
// stale and listed again by --todo. The translation itself is done by an AI
// session from the --todo output, with tools/i18n/glossary.md in hand; the
// JSON it hands back to --apply maps "section/key" to the translated text.
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath, pathToFileURL } from "node:url";
import { REFERENCE, REFERENCE_CATEGORIES } from "../../live/src/reference.js";

const root = fileURLToPath(new URL("../../", import.meta.url));
const packDir = path.join(root, "live/src/i18n");

const hash = (text) => createHash("sha1").update(text).digest("hex").slice(0, 8);

// The snippet's description, as live/index.html's loadBrowseFile reads it.
function leadingComment(file) {
  const lead = [];
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    const m = /^\s*;+\s?(.*)$/.exec(line);
    if (!m) break;
    lead.push(m[1]);
  }
  return lead.join(" ").replace(/\s+/g, " ").trim();
}

function englishTexts() {
  const items = [];
  for (const [id, label] of REFERENCE_CATEGORIES) items.push({ section: "categories", key: id, en: label });
  for (const e of REFERENCE) items.push({ section: "reference", key: e.name, en: e.summary });
  const index = JSON.parse(fs.readFileSync(path.join(root, "live/snippets/index.json"), "utf8"));
  for (const p of index) // keyed without the folder, so "snippets/notation/x.mmlisp" names it
    items.push({ section: "snippets", key: p.replace(/^snippets\//, ""), en: leadingComment(path.join(root, "live", p)) });
  return items;
}

async function loadPack(lang) {
  const file = path.join(packDir, `${lang}.js`);
  if (!fs.existsSync(file)) return { language: lang, categories: {}, reference: {}, snippets: {} };
  return (await import(pathToFileURL(file).href)).default;
}

function packLanguages() {
  return fs.readdirSync(packDir).filter((f) => f.endsWith(".js")).map((f) => f.slice(0, -3)).sort();
}

// What a pack lacks: missing and stale texts, and the orphans it still holds.
function audit(pack, items) {
  const missing = [], stale = [];
  const seen = new Set();
  for (const it of items) {
    seen.add(`${it.section}/${it.key}`);
    const row = pack[it.section]?.[it.key];
    if (!row) missing.push(it);
    else if (row[0] !== hash(it.en)) stale.push(it);
  }
  const orphans = [];
  for (const section of ["categories", "reference", "snippets"])
    for (const key of Object.keys(pack[section] ?? {}))
      if (!seen.has(`${section}/${key}`)) orphans.push(`${section}/${key}`);
  return { missing, stale, orphans };
}

const js = (s) => JSON.stringify(s);

function writePack(lang, pack, items) {
  const sections = { categories: [], reference: [], snippets: [] };
  for (const it of items) {
    const row = pack[it.section]?.[it.key];
    if (row) sections[it.section].push(`    ${js(it.key)}: [${js(row[0])}, ${js(row[1])}],`);
  }
  const body = Object.entries(sections)
    .map(([name, rows]) => `  ${name}: {\n${rows.join("\n")}\n  },`).join("\n");
  const text = `// Generated by tools/scripts/i18n-sync.mjs from the English in reference.js
// and the snippets — do not edit by hand: run the sync, translate its --todo,
// and --apply the result. Each text is [hash of the English, translation].
export default {
  language: ${js(lang)},
${body}
};
`;
  fs.writeFileSync(path.join(packDir, `${lang}.js`), text);
}

const args = process.argv.slice(2);
const items = englishTexts();

if (args[0] === "--todo") {
  const lang = args[1];
  if (!lang) throw new Error("--todo needs a language");
  const { missing, stale } = audit(await loadPack(lang), items);
  const todo = {};
  for (const it of [...missing, ...stale]) todo[`${it.section}/${it.key}`] = it.en;
  process.stdout.write(JSON.stringify(todo, null, 2) + "\n");
} else if (args[0] === "--apply") {
  const [, lang, file] = args;
  if (!lang || !file) throw new Error("--apply needs a language and a JSON file");
  const pack = await loadPack(lang);
  const byKey = new Map(items.map((it) => [`${it.section}/${it.key}`, it]));
  const given = JSON.parse(fs.readFileSync(file, "utf8"));
  let n = 0;
  for (const [k, text] of Object.entries(given)) {
    const it = byKey.get(k);
    if (!it) { console.error(`${k}: no such text, skipped`); continue; }
    if (typeof text !== "string" || !text.trim()) { console.error(`${k}: empty, skipped`); continue; }
    (pack[it.section] ??= {})[it.key] = [hash(it.en), text.trim()];
    n++;
  }
  const { orphans } = audit(pack, items);
  writePack(lang, pack, items); // writes the English's order, which drops the orphans
  console.log(`${lang}: ${n} text(s) applied${orphans.length ? `, ${orphans.length} orphan(s) dropped` : ""}`);
} else {
  const problems = [];
  for (const lang of packLanguages()) {
    const { missing, stale, orphans } = audit(await loadPack(lang), items);
    for (const it of missing) problems.push(`${lang}: ${it.section}/${it.key} is not translated`);
    for (const it of stale) problems.push(`${lang}: ${it.section}/${it.key} is stale (the English changed)`);
    for (const k of orphans) problems.push(`${lang}: ${k} no longer exists in the English`);
  }
  if (problems.length) {
    for (const p of problems) console.error(p);
    throw new Error(`${problems.length} i18n problem(s) — see tools/README.md § i18n`);
  }
  console.log(`i18n checks passed: ${items.length} texts in ${packLanguages().join(", ")}`);
}
