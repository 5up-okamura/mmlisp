// Emit drv/68k/tables.c from the SAME code the reference uses (driver.md §12.6).
//
// The sequencer's constant tables are the one place where the C and
// drv-player.js could silently disagree, so neither side derives them: both
// take them from live/src/ir-utils.js, one at runtime and one through this
// generator. Divergence stays structurally impossible.
//
//   node tools/gen-c-tables.mjs [--out DIR]
//
// `--out` exists because the VERIFICATION tools compile these files too, and
// every one of them used to regenerate them in place and leave the tree
// modified. The DEFAULT still writes drv/68k, which is what install-sgdk.mjs
// copies from and what a product build reads; the gates pass a directory of
// their own (tools/c-tables.mjs).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  midiToFnumBlock,
  PSG_MASTER_CLOCK,
  velToTlAtten,
  volToTlOffset,
  velToPsgAtten,
  volToPsgOffset,
  fmCarrierOpsForAlg,
  OP_ADDR_OFFSET,
} from "../../live/src/ir-utils.js";
import { SIN_LUT, pcmBankStamp } from "../../live/src/mmb.js";
import { ENGINE_IMAGES } from "../../live/src/engine-images.js";

const argv = process.argv.slice(2);
const outIdx = argv.indexOf("--out");
if (outIdx >= 0 && !argv[outIdx + 1]) {
  console.error("gen-c-tables: --out needs a directory");
  process.exit(2);
}
const k68 = outIdx >= 0 ? argv[outIdx + 1]
  : join(dirname(fileURLToPath(import.meta.url)), "..", "68k");
mkdirSync(k68, { recursive: true });
const dst = join(k68, "tables.c");

// The engine images' rate stamps, for the C mirrors. A HEADER and not part of
// tables.c because mmlispseq.h includes it: mml_load_samples refuses a bank
// baked for another image, which is what makes a rate mismatch fail loudly
// instead of playing at the wrong pitch. Generated from the one definition,
// live/src/engine-images.js (itself generated from the images as built).
const stamps = [1, 2, 3].map((v) => pcmBankStamp(ENGINE_IMAGES[v].rateHz));
writeFileSync(
  join(k68, "mml_rate.h"),
  `/* GENERATED by tools/gen-c-tables.mjs from live/src/engine-images.js — do not edit. */
#ifndef MML_RATE_H
#define MML_RATE_H

/* The DAC rate, rounded, of the engine image for 1, 2 and 3 PCM voices: the
 * stamp a sample bank baked for that image carries (mmb.md §10). */
#define MML_PCM_STAMP_1 ${stamps[0]}
#define MML_PCM_STAMP_2 ${stamps[1]}
#define MML_PCM_STAMP_3 ${stamps[2]}

/* RATE-STAMPS ${stamps.join(" ")} — see tools/rate-mirrors.mjs. */

#endif
`,
);

const rows = (vals, perLine, fmt = String) => {
  const out = [];
  for (let i = 0; i < vals.length; i += perLine) {
    out.push("    " + vals.slice(i, i + perLine).map(fmt).join(", ") + ",");
  }
  return out.join("\n");
};

const fnumBlock = [];
for (let n = 0; n < 128; n++) {
  const { fnum, block } = midiToFnumBlock(n);
  fnumBlock.push(((block & 0x07) << 11) | (fnum & 0x7ff));
}
const psgPeriod = [];
for (let n = 0; n < 128; n++) {
  const freq = 440 * Math.pow(2, (n - 69) / 12);
  psgPeriod.push(Math.max(1, Math.min(1023, Math.round(PSG_MASTER_CLOCK / (32 * freq)))));
}
// Level offsets in QUARTER steps: composition sums them and rounds once, which
// is how the runtime stays integer-only while matching the player's
// float-sum-then-quantize inside the documented band (driver.md §7).
const velTl4 = [...Array(16)].map((_, v) => Math.round(velToTlAtten(v) * 4));
const volTl4 = [...Array(32)].map((_, v) => Math.round(volToTlOffset(v) * 4));
const velPsg4 = [...Array(16)].map((_, v) => Math.round(velToPsgAtten(v) * 4));
const volPsg4 = [...Array(32)].map((_, v) => Math.round(volToPsgOffset(v) * 4));
const carrierMask = [...Array(8)].map((_, alg) =>
  fmCarrierOpsForAlg(alg).reduce((m, op) => m | (1 << op), 0),
);

writeFileSync(
  dst,
  `/* GENERATED by tools/gen-c-tables.mjs from live/src/ir-utils.js — do not edit.
 *
 * The sequencer's constant tables (driver.md §7, §8, §12.6). Both this and
 * drv-player.js take them from the same source, so the two cannot disagree.
 */
#include "mmlispseq.h"

/* note -> (block << 11) | fnum */
const uint16_t MML_FNUM_BLOCK[128] = {
${rows(fnumBlock, 8)}
};

/* note -> SN76489 tone period (10 bit) */
const uint16_t MML_PSG_PERIOD[128] = {
${rows(psgPeriod, 8)}
};

/* Level offsets, quarter steps */
const int16_t MML_VEL_TL4[16] = {
${rows(velTl4, 8)}
};
const int16_t MML_VOL_TL4[32] = {
${rows(volTl4, 8)}
};
const int16_t MML_VEL_PSG4[16] = {
${rows(velPsg4, 8)}
};
const int16_t MML_VOL_PSG4[32] = {
${rows(volPsg4, 8)}
};

/* algorithm -> bitmask of carrier operators */
const uint8_t MML_CARRIER_MASK[8] = {
${rows(carrierMask, 8)}
};

/* op1..op4 in OPN2 register space */
const uint8_t MML_OP_ADDR_OFFSET[4] = {
${rows([...OP_ADDR_OFFSET], 4)}
};

/* sin loop waveform, (1 - cos(2*pi*t/256)) / 2 quantised to 0..255. The only
 * curve that needs a table; the other seven are computed (driver.md §12.6). */
const uint8_t MML_SIN_LUT[256] = {
${rows([...SIN_LUT], 12)}
};
`,
);
console.log(`wrote ${dst}`);
